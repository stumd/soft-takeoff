// Fridge contents are described once, in the story, and rendered both on the
// fridge door in 3D and as a close-up in the side panel.
export function fridgeEntity(notes, seed = 0) {
  const kinds = notes.map((n) => {
    if (n.k === 'drawing') return 'draw';
    if (n.k === 'photo') return { k: 'photo', c: n.tint || '#7a8a6a' };
    if (n.k === 'letter') return 'letter';
    if (n.k === 'menu') return 'menu';
    if (n.k === 'card') return { k: 'card', c: n.c || '#2f3a5a' };
    if (n.k === 'clip') return 'w';
    return n.c || 'y';
  });
  return E('fridge', 'fridge', { notes: kinds, seed });
}

